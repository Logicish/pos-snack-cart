// 2026-08-26 — a soft ESP32 reset (e.g. a firmware reflash) doesn't necessarily power-
// cycle the GM65 (confirmed ambiguous earlier — see project memory), so it can come back
// up still holding whatever live/RAM state it had *before* the reset — caught for real
// when a reflash landed while the screensaver had it in Manual/scan-off mode, and it
// stayed off after boot with nothing to notice or correct it. Force the known-good
// locked config on every boot rather than trusting whatever state carried over. RAM-only
// writes (no EEPROM save — this isn't re-provisioning, just re-asserting), matching
// screen_gm65_test.cpp's act_setup_defaults() values exactly (see project memory:
// project_gm65_settings_lockin) but duplicated here rather than shared, per this
// codebase's established per-file self-contained convention for GM65 command helpers.
static void gm65_write_reg(uint8_t addr_hi, uint8_t addr_lo, uint8_t data) {
    const uint8_t cmd[9] = {0x7E, 0x00, 0x08, 0x01, addr_hi, addr_lo, data, 0xAB, 0xCD};
    scanner.write(cmd, 9);
}

// Boot scanner check, 2026-10-02: did the GM65 answer the boot writes at all, and do its
// registers read back as the locked config? Reads 0x0000-0x000D in one frame -- same
// command and reply layout as screen_gm65_settings.cpp (4-byte header {0x02 0x00 Types Lens},
// then the data, then 2 CRC bytes; the data does NOT start at offset 0). Also reports
// the setup-code lock (reg 0x0003 = 0x03, see screen_gm65_test.cpp) so a cart that ships
// with it off says so. Results go to the boot log and the Admin Menu alert banner.
// Slide Free board files, 2026-10-02 -- the game plays however many tierN.txt files it finds
// (stopping at the first gap), so a missing or empty one silently shrinks it rather than
// erroring. The cart ships with 5 (generated by tools/tilt_lab.py, copies in tools/slidefree/).
#define SLIDE_FREE_TIERS 5
static void boot_check_slide_free() {
    char missing[48] = "";
    for (int t = 1; t <= SLIDE_FREE_TIERS; t++) {
        char path[32];
        snprintf(path, sizeof(path), "/slidefree/tier%d.txt", t);
        File f = SD.open(path, FILE_READ);
        bool ok = f && f.size() > 0;
        if (f) f.close();
        if (ok) continue;
        size_t len = strlen(missing);
        snprintf(missing + len, sizeof(missing) - len, "%stier%d", len ? "+" : "", t);
    }
    if (missing[0]) {
        boot_log_note("slide_free_missing", "%s", missing);
        system_alerts_add_boot_issue("SLIDE FREE BOARD FILES MISSING");
    } else {
        boot_log_note("slide_free", "ok");
    }
}

#define GM65_READ_COUNT 0x0E
// Sends the 14-register read and collects whatever comes back until the bus goes quiet.
static size_t gm65_read_regs_raw(uint8_t *buf, size_t cap) {
    const uint8_t cmd[9] = {0x7E, 0x00, 0x07, 0x01, 0x00, 0x00, GM65_READ_COUNT, 0xAB, 0xCD};
    scanner.write(cmd, 9);

    size_t n = 0;
    uint32_t start = millis(), last_rx = 0;
    while (millis() - start < 500) {            // fault-guard if the module never answers
        if (scanner.available()) {
            while (scanner.available()) {
                int b = scanner.read();
                if (n < cap) buf[n++] = (uint8_t)b;
            }
            last_rx = millis();
        } else if (n > 0 && millis() - last_rx >= 40) {
            break;                              // reply received, bus quiet since
        }
        delay(1);
    }
    return n;
}

static void boot_check_scanner(bool acked) {
    uint8_t buf[64];
    size_t n = 0;
    const uint8_t *regs = nullptr;

    // Two tries. On the first boot after a reflash (2026-10-02, real hardware) the module
    // answers slower: one boot-write ACK (02 00 00 01 00 33 31) landed in the read window
    // and the read reply never showed. A second ask, after the line is quiet, gets it.
    for (int attempt = 0; attempt < 2 && !regs; attempt++) {
        if (attempt > 0) {
            delay(100);
            while (scanner.available()) scanner.read();
        }
        n = gm65_read_regs_raw(buf, sizeof(buf));

        // Prefer a frame whose Lens byte matches the count asked for; failing that, take any
        // {0x02 0x00} frame with room for all 14 registers that isn't a 7-byte write ACK
        // (02 00 00 01 00 33 31 -- Lens 0x01).
        for (int pass = 0; pass < 2 && !regs; pass++) {
            for (size_t i = 0; i + 4 + GM65_READ_COUNT <= n; i++) {
                if (buf[i] != 0x02 || buf[i + 1] != 0x00) continue;
                bool lens_ok = pass == 0 ? buf[i + 3] == GM65_READ_COUNT : buf[i + 3] != 0x01;
                if (lens_ok) { regs = buf + i + 4; break; }
            }
        }
        if (!regs && attempt == 0) Serial.println("[SCAN] boot readback missed -- asking once more");
    }

    if (!regs) {
        // Keep what did arrive, so the boot log shows the real reply to fix the parser from.
        char raw[3 * 24 + 8];
        int len = snprintf(raw, sizeof(raw), "%u:", (unsigned)n);
        for (size_t i = 0; i < n && i < 24 && len < (int)sizeof(raw) - 3; i++) {
            len += snprintf(raw + len, sizeof(raw) - len, "%02X", buf[i]);
        }
        boot_log_note("scanner_raw", "%s", raw);
        boot_log_note("scanner", "%s", acked ? "no_readback" : "NOT_RESPONDING");
        if (!acked) system_alerts_add_boot_issue("SCANNER NOT RESPONDING");
        else        system_alerts_add_boot_issue("SCANNER SETTINGS UNREADABLE");
        return;
    }

    bool settings_ok = regs[0x00] == 0x57 && regs[0x07] == 0x00 && regs[0x0A] == 0x64;
    bool qr_locked   = regs[0x03] == 0x03;
    boot_log_note("scanner", "%s", settings_ok ? "ok" : "SETTINGS_MISMATCH");
    boot_log_note("scanner_regs", "%02X/%02X/%02X", regs[0x00], regs[0x07], regs[0x0A]);
    boot_log_note("qr_config_lock", "%s", qr_locked ? "on" : "OFF");
    if (!settings_ok) system_alerts_add_boot_issue("SCANNER SETTINGS DIDN'T STICK");
    if (!qr_locked)   system_alerts_add_boot_issue("SCANNER SETUP-CODE LOCK IS OFF");
}

